// buildRealClientHello drives the actual fingerprint+uTLS code path to
// produce a real yandex-android ClientHello, wrapped in a TLS record, so
// the parser is exercised against genuine wire bytes rather than hand
// crafted fixtures.
func buildRealClientHello(t *testing.T, sessionID [32]byte) ([]byte, [32]byte) {
	t.Helper()

	params := fingerprint.YandexAndroidParams{
		Ext51764Prefixes:    []string{"d67909", "839a648c9b2d01", "82df1302"},
		Ext51764BaseVariant: "00cc04d679090f04d679090e08839a648c9b2d011308839a648c9b2d010708839a648c9b2d010c04d679090308839a648c9b2d010d04d679090c04d679090a0582df13021404d67909040582df13020104d679090504d679090808839a648c9b2d01080582df13020d04d679090b08839a648c9b2d01090582df13020608839a648c9b2d010a0582df13021304d679090604d67909090582df1302120582df13020f04d679090d08839a648c9b2d010b04d67909010582df13020e04d679090208839a648c9b2d011204d6790907",
		Ext51764RotateDays:  [2]int{3, 7},
		EchPayloadLens:      []int{144, 176},
	}
	deviceSeed := make([]byte, 32)
	if _, err := rand.Read(deviceSeed); err != nil {
		t.Fatal(err)
	}

	spec, err := fingerprint.BuildClientHelloSpec(deviceSeed, time.Now(), params, "example.invalid")
	if err != nil {
		t.Fatalf("BuildClientHelloSpec: %v", err)
	}

	clientConn, serverConn := net.Pipe()
	defer clientConn.Close()
	defer serverConn.Close()
	uconn := utls.UClient(clientConn, &utls.Config{ServerName: "example.invalid", InsecureSkipVerify: true}, utls.HelloCustom)
	if err := uconn.ApplyPreset(spec); err != nil {
		t.Fatalf("ApplyPreset: %v", err)
	}

	uconn.HandshakeState.Hello.SessionId = sessionID[:]
	if err := uconn.MarshalClientHelloNoECH(); err != nil {
		t.Fatalf("MarshalClientHelloNoECH: %v", err)
	}

	ecdhe := uconn.HandshakeState.State13.KeyShareKeys.Ecdhe
	if ecdhe == nil {
		t.Fatal("no X25519 ephemeral key generated by ApplyPreset")
	}
	var pub [32]byte
	copy(pub[:], ecdhe.PublicKey().Bytes())

	raw := uconn.HandshakeState.Hello.Raw
	record := make([]byte, 5+len(raw))
	record[0] = 0x16
	binary.BigEndian.PutUint16(record[1:3], 0x0301)
	binary.BigEndian.PutUint16(record[3:5], uint16(len(raw)))
	copy(record[5:], raw)
	return record, pub
}

func TestPeekClientHelloRoundTrip(t *testing.T) {
	var sessionID [32]byte
	if _, err := rand.Read(sessionID[:]); err != nil {
		t.Fatal(err)
	}

	record, wantPub := buildRealClientHello(t, sessionID)

	got, err := PeekClientHello(bytes.NewReader(record))
	if err != nil {
		t.Fatalf("PeekClientHello: %v", err)
	}
	if !bytes.Equal(got.SessionID, sessionID[:]) {
		t.Fatalf("session id mismatch: got %x want %x", got.SessionID, sessionID)
	}
	if !bytes.Equal(got.ClientX25519, wantPub[:]) {
		t.Fatalf("client X25519 key mismatch: got %x want %x", got.ClientX25519, wantPub)
	}
	if got.SNI != "example.invalid" {
		t.Fatalf("SNI mismatch: got %q", got.SNI)
	}

	ad := got.ClientHelloAD()
	if len(ad) != len(got.Raw) {
		t.Fatalf("AD length mismatch")
	}
	for i := 0; i < 32; i++ {
		if ad[got.SessionIDOff+i] != 0 {
			t.Fatalf("AD session_id span not zeroed at byte %d", i)
		}
	}
	// everything outside the session_id span must be untouched
	adCopy := append([]byte(nil), ad...)
	copy(adCopy[got.SessionIDOff:got.SessionIDOff+32], got.Raw[got.SessionIDOff:got.SessionIDOff+32])
	if !bytes.Equal(adCopy, got.Raw) {
		t.Fatalf("AD differs from Raw outside the session_id span")
	}
}

func TestPeekClientHelloMalformedInputDoesNotPanic(t *testing.T) {
	inputs := [][]byte{
		{},
		{0x16},
		{0x16, 0x03, 0x01, 0x00, 0x01, 0x01}, // truncated handshake body
		{0x17, 0x03, 0x01, 0x00, 0x00},       // not a handshake record
		append([]byte{0x16, 0x03, 0x01, 0x00, 0x04}, []byte{0x01, 0xff, 0xff, 0xff}...), // huge declared length
	}
	for i, in := range inputs {
		if _, err := PeekClientHello(bytes.NewReader(in)); err == nil {
			t.Errorf("input %d: expected error, got nil", i)
		}
	}
}
